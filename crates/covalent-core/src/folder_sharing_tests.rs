#[test]
fn offer_tampering_never_verifies() {
    let records = records(None);
    let mut variants = Vec::new();
    let mut changed = records.offer.clone();
    changed.label.push('!');
    variants.push(changed);
    let mut changed = records.offer.clone();
    changed.folder_id = Uuid::new_v4();
    variants.push(changed);
    let mut changed = records.offer.clone();
    changed.source_engine.direct_address = "203.0.113.11:22000".to_owned();
    variants.push(changed);
    let mut changed = records.offer.clone();
    changed.nonce = URL_SAFE_NO_PAD.encode([7_u8; 24]);
    variants.push(changed);
    let mut changed = records.offer.clone();
    tamper_first(&mut changed.signature);
    variants.push(changed);
    for changed in variants {
        assert!(
            verify_folder_share_offer(
                &changed,
                &records.source.public_identity(),
                records.target.device_id(),
            )
            .is_err()
        );
    }
}

