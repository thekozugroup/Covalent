#[test]
fn acceptance_digest_signature_and_time_substitution_fail() {
    let records = records(None);
    let mut variants = Vec::new();
    let mut changed = records.acceptance.clone();
    changed.offer_digest = "0".repeat(64);
    variants.push(changed);
    let mut changed = records.acceptance.clone();
    changed.accepted_at_unix_ms += 1;
    variants.push(changed);
    let mut changed = records.acceptance.clone();
    tamper_first(&mut changed.signature);
    variants.push(changed);
    for changed in variants {
        assert!(
            verify_folder_share_acceptance(
                &records.offer,
                &changed,
                &records.source.public_identity(),
                &records.target.public_identity(),
            )
            .is_err()
        );
    }
    let mut too_late = records.acceptance.clone();
    too_late.accepted_at_unix_ms = records.offer.expires_at_unix_ms;
    assert_eq!(
        verify_folder_share_acceptance(
            &records.offer,
            &too_late,
            &records.source.public_identity(),
            &records.target.public_identity(),
        ),
        Err(FolderSharingError::InvalidRecord)
    );
}

